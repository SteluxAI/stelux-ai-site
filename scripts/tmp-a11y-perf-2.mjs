// Isolation probe: what keeps the main thread busy while idle (mobile CPU4x + desktop)
import { chromium } from 'playwright'
const BASE = process.env.SHOT_URL || 'http://localhost:4173/'
const browser = await chromium.launch()
async function idle({ name, mobile, cpu, reduced, style, js, scrollTo }) {
  const viewport = mobile ? { width: 375, height: 812 } : { width: 1440, height: 900 }
  const ctx = await browser.newContext({ viewport, isMobile: !!mobile, hasTouch: !!mobile, deviceScaleFactor: mobile ? 3 : 1, reducedMotion: reduced ? 'reduce' : 'no-preference' })
  const page = await ctx.newPage()
  const cdp = await ctx.newCDPSession(page)
  if (cpu) await cdp.send('Emulation.setCPUThrottlingRate', { rate: cpu })
  await cdp.send('Performance.enable')
  await page.goto(BASE, { waitUntil: 'networkidle' })
  if (style) await page.addStyleTag({ content: style })
  if (js) await page.evaluate(js)
  if (scrollTo) await page.evaluate((sel) => { const y = document.querySelector(sel).getBoundingClientRect().top + scrollY - 100; if (window.__lenis) window.__lenis.scrollTo(y, { immediate: true, force: true, lock: true }); scrollTo(0, y) }, scrollTo)
  await page.waitForTimeout(2500)
  const get = async () => Object.fromEntries((await cdp.send('Performance.getMetrics')).metrics.map((m) => [m.name, m.value]))
  const a = await get()
  await page.waitForTimeout(4000)
  const b = await get()
  const dt = b.Timestamp - a.Timestamp
  const pct = (k) => ((b[k] - a[k]) / dt * 100).toFixed(1).padStart(5) + '%'
  console.log(`[${name.padEnd(52)}] task=${pct('TaskDuration')} script=${pct('ScriptDuration')} layout=${pct('LayoutDuration')} style=${pct('RecalcStyleDuration')} layouts/s=${((b.LayoutCount - a.LayoutCount) / dt).toFixed(0).padStart(3)} recalcs/s=${((b.RecalcStyleCount - a.RecalcStyleCount) / dt).toFixed(0).padStart(3)}`)
  await ctx.close()
}
const pauseSmil = () => document.querySelectorAll('svg').forEach((s) => s.pauseAnimations && s.pauseAnimations())
const M = { mobile: true, cpu: 4 }
console.log('--- mobile 375 @3x, CPU 4x, hero in view ---')
await idle({ name: 'baseline', ...M })
await idle({ name: 'SMIL paused', ...M, js: pauseSmil })
await idle({ name: 'CSS animations off', ...M, style: '*,*::before,*::after{animation:none!important}' })
await idle({ name: 'live-dot animation off only', ...M, style: '.live-dot{animation:none!important}' })
await idle({ name: 'sheen (dash-gradient::after) off only', ...M, style: '.dash-gradient::after{animation:none!important}' })
await idle({ name: 'SMIL paused + CSS animations off', ...M, js: pauseSmil, style: '*,*::before,*::after{animation:none!important}' })
await idle({ name: 'SMIL + CSS off + sky hidden', ...M, js: pauseSmil, style: '*,*::before,*::after{animation:none!important} #aurora{display:none!important}' })
await idle({ name: 'SMIL + CSS off + sky hidden + no backdrop', ...M, js: pauseSmil, style: '*,*::before,*::after{animation:none!important} #aurora{display:none!important} *{backdrop-filter:none!important}' })
await idle({ name: 'reduced-motion context', ...M, reduced: true })
await idle({ name: 'reduced-motion context + SMIL paused', ...M, reduced: true, js: pauseSmil })
await idle({ name: 'at #pricing (hero offscreen)', ...M, scrollTo: '#pricing' })
await idle({ name: 'at #pricing + SMIL paused', ...M, scrollTo: '#pricing', js: pauseSmil })
console.log('--- desktop 1440, no CPU throttle, hero in view ---')
await idle({ name: 'baseline' })
await idle({ name: 'SMIL paused', js: pauseSmil })
await idle({ name: 'CSS animations off', style: '*,*::before,*::after{animation:none!important}' })
await idle({ name: 'SMIL paused + CSS animations off', js: pauseSmil, style: '*,*::before,*::after{animation:none!important}' })
await idle({ name: 'reduced-motion + SMIL paused', reduced: true, js: pauseSmil })
await idle({ name: 'at #pricing', scrollTo: '#pricing' })
await idle({ name: 'at #pricing + SMIL paused', scrollTo: '#pricing', js: pauseSmil })
await browser.close()
